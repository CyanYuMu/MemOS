-- 控制台保存密钥明文，供有写权限的成员在列表里再次复制。
--
-- 既有设计只存 SHA-256 哈希，明文仅在签发响应里出现一次：安全，但“复制失败 / 弹窗
-- 关早了 / 粘贴少一段”就只能重新生成（那是换密钥，不是再看一眼）。本部署是同集群内网
-- 控制台、能读库的人本来就有等价权限，所以按部署方要求保存明文，换取可用的复制体验。
--
-- 边界：
--   * `raw` 只由控制台列表接口在**写权限**（editor/owner/平台管理员）下下发；
--     viewer 仍只拿前缀掩码。API key 是租户级凭据，能复制就能绕过角色写记忆。
--   * 历史行（迁移前签发、旧网关导入的 legacy Key）raw 为空，无法回溯；列表显示掩码
--     并提示重新生成。部署配置里的静态 Key 在下一次启动 Bootstrap 时补上明文。
ALTER TABLE tokens ADD COLUMN raw TEXT NOT NULL DEFAULT '';
